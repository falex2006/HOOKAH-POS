import assert from 'node:assert/strict';
import fs from 'node:fs';

const lock = fs.readFileSync('lock.js', 'utf8');
const distLock = fs.readFileSync('dist/lock.js', 'utf8');
const server = fs.readFileSync('server.js', 'utf8');
const css = fs.readFileSync('style.css', 'utf8');
const authCss = fs.readFileSync('auth-smoke.css', 'utf8');
assert.match(lock, /class="auth-smoke-backdrop" aria-hidden="true"/, 'screen lock uses the shared video backdrop host');
assert.match(distLock, /class="auth-smoke-backdrop" aria-hidden="true"/, 'dist screen lock uses the shared video backdrop host');
assert.match(lock, /auth-smoke\.css\?rev=2/);
assert.match(authCss, /\.auth-smoke-video[,{][^}]*position:absolute/);
assert.doesNotMatch(css, /@keyframes smokeRise|@keyframes loginSmoke/);
assert.doesNotMatch(authCss, /@keyframes smokeRise|@keyframes loginSmoke/);
assert.match(lock, /api\/session\/unlock/);
assert.match(lock, /if \(!token\) return;/, 'lock screen must not recover a bearer token from a trusted cookie before PIN return');
assert.doesNotMatch(lock, /if \(!token\)[\s\S]{0,240}fetch\('\/api\/session'/, 'lock screen must not call /api/session to bootstrap localStorage token from cookie');
assert.match(lock, /value\.length !== 4/);
assert.match(lock, /pattern="\[0-9\]\{4\}"/);
assert.match(server, /pin_not_configured/);
assert.match(server, /invalid_pin/);
assert.match(server, /verifyPassword\(pin/);
assert.match(server, /pinUnlockAttempts\.get\(attemptKey\)/, 'PIN verification has a dedicated guessing limit');
assert.match(lock, /crm_screen_locked_user_/);
assert.match(lock, /window\.addEventListener\('storage'/, 'lock state synchronizes across tabs');
assert.match(lock, /document\.addEventListener\('click'[\s\S]*?#lock-screen-button[\s\S]*?lock\('manual'\)/, 'lock button clicks are delegated so rerendered headers keep working');
assert.match(lock, /if \(!user\.pinConfigured && !await refreshUserFromSession\(\)\).*window\.__openLockSettings/, 'a user without a PIN cannot become trapped behind a lock overlay');
assert.match(lock, /event\.newValue === 'locked' && user\.pinConfigured/, 'a stale lock signal cannot force an account without PIN into a blocked state');
assert.doesNotMatch(lock, /user\.pinConfigured\s*=\s*true;\s*lock\('manual'\)/, 'cross-tab lock must never invent PIN configuration');
assert.match(lock, /event\.key === 'crm_session_user'/, 'new PIN state is synchronized before another tab applies a lock signal');
assert.match(lock, /sessionEventKey = 'crm_session_event'/, 'logout is broadcast as a session-ended event, not as an unlock signal');
assert.match(lock, /notice\.action === 'logout'.*redirectToLogin\(\)/, 'a stale authenticated tab redirects after another tab logs out');
assert.match(lock, /event\.newValue !== activeToken/, 'a stale tab redirects after its bearer session is replaced');
assert.match(lock, /autoLockEnabled = Boolean\(user\.pinConfigured\)/, 'PIN added in another tab enables inactivity locking without a reload');
assert.match(lock, /refreshUserFromSession[\s\S]*?fetch\('\/api\/session'/, 'lock can recover PIN state from a live trusted session before opening settings');
assert.match(lock, /event\.newValue\?\.startsWith\('unlocked:'\)/, 'only a successful, explicit unlock event dismisses another tab lock');
assert.doesNotMatch(lock, /event\.newValue === null && locked/, 'removing a storage key cannot impersonate a successful PIN unlock');
console.log('LOCAL LOCK CONTRACT: PASS (HTTP PIN, four-digit validation, cross-tab logout/session replacement, PIN-state synchronization, explicit unlock signal and no-PIN guard)');
