import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');
const server = read('../server.js');
const db = read('../db.js');
const schema = read('../schema.sql');
const migration = read('../migrations/084_order_item_sales_attribution.sql');
const app = read('../app.js');
const route = (from, to) => {
  const start = server.indexOf(from);
  const end = server.indexOf(to, start);
  assert.notEqual(start, -1, `route marker exists: ${from}`);
  assert.notEqual(end, -1, `route boundary exists: ${to}`);
  return server.slice(start, end);
};

const add = route("if (itemMatch && req.method === 'POST')", 'const itemAction = pathname.match');
const edit = route("if (itemAction && (req.method === 'PATCH' || req.method === 'DELETE'))", 'const paymentPath = pathname.match');

for (const [name, source] of [['schema', schema], ['migration', migration]]) {
  assert.match(source, /sales_employee_id uuid/, `${name} stores the sale employee`);
  assert.match(source, /sold_at timestamptz/, `${name} stores the sale time`);
  assert.match(source, /CHECK \(\(sales_employee_id IS NULL AND sold_at IS NULL\) OR \(sales_employee_id IS NOT NULL AND sold_at IS NOT NULL\)\)/, `${name} keeps employee and time nullable as a pair`);
  assert.match(source, /order_items_sales_attribution_validate/, `${name} validates employee/venue attribution`);
  assert.match(source, /u\.is_active=true AND u\.deleted_at IS NULL/, `${name} excludes inactive employees`);
}

assert.match(add, /req\.user\?\.id/, 'seller identity comes from the authenticated request');
assert.match(add, /u\.is_active=true AND u\.deleted_at IS NULL[\s\S]*organization_memberships/, 'seller must be active and eligible for this venue or organization');
assert.match(add, /sales_attribution_server_managed/, 'seller and time cannot be forged in the request');
assert.match(add, /sales_employee_session_required/, 'new sales require a valid employee session');
assert.match(add, /INSERT INTO order_items[\s\S]*sales_employee_id,sold_at/, 'new POST creates an attributed sale row');
assert.doesNotMatch(add, /UPDATE order_items SET quantity=/, 'new sales are not merged into prior rows');
assert.match(add, /now\(\)/, 'database timestamp is generated by PostgreSQL');
assert.match(edit, /UPDATE order_items SET quantity=\$1[\s\S]*sales_employee_id AS "salesEmployeeId",sold_at AS "soldAt"/, 'quantity edits return existing attribution');
assert.match(db, /'salesEmployeeId', oi\.sales_employee_id[\s\S]*'salesEmployeeName', sales_employee\.full_name[\s\S]*'soldAt', oi\.sold_at/, 'order reload returns attribution fields');
assert.match(app, /const existing=\(order\.items\|\|\[\]\)\.find\(\(entry\)=>entry\.id===created\.id\)/, 'catalog add does not merge by product');
assert.match(app, /isPlus\?apiJson\(`\/api\/orders\/\$\{orderId\}\/items`/, 'floor plus action posts a separate portion');
assert.match(app, /Автор продажи не зафиксирован/, 'legacy items are visibly marked unknown in the floor UI');
assert.match(app, /<span><span>\$\{escapeFloorText\(displayProductName\([\s\S]*?order-item-attribution[\s\S]*?<\/small><\/span><span class="quantity-control">/, 'seller/time stay inside the product grid cell so quantity and total keep their established columns');

assert.match(app, /salesAttributionStatus:'demo_unverified'/, 'static local items are explicitly untrusted');
assert.match(app, /staticStaffDemo\(\)\|\|item\.salesAttributionStatus==='demo_unverified'/, 'legacy static local rows are also rendered as untrusted');
assert.match(app, /ДЕМО · не подтверждено/, 'the UI marks local-storage seller metadata as demo-only');
assert.match(app, /локально ·/, 'the UI labels local browser timestamps');

