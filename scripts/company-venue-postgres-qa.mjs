    await blocker.query('BEGIN');
    await blocker.query('SELECT id FROM venues WHERE id=$1 FOR UPDATE', [venueA]);
    const racingSave = request('/api/venue', 'PATCH', { expectedVenueId: venueA, name: 'Late Save Into A' });
