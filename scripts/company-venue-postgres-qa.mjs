  assert.equal(newZone.status, 201, JSON.stringify(newZone.body));
  const newTable = await request('/api/floor/tables', 'POST', { expectedVenueId: venueB, zoneId: newZone.body.id, name: 'QA B New Table', capacity: 2 });
  assert.equal(newTable.status, 201, JSON.stringify(newTable.body));
