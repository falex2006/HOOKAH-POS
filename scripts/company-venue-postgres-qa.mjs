  assert.equal((await request(`/api/floor/zones/${newZone.body.id}`, 'DELETE', { expectedVenueId: venueB })).status, 200);
  const second = await request('/api/venue');
  assert.equal(second.status, 200); assert.equal(second.body.id, venueB); assert.equal(second.body.name, 'QA Venue B'); assert.equal(second.body.vipRoomMinimums.vip_room_1, 2200);
  const stale = await request('/api/venue', 'PATCH', { expectedVenueId: venueA, name: 'Wrong Venue' });
  assert.equal(stale.status, 409, JSON.stringify(stale.body));
