  assert.equal(floorB.body.zones.some((zone) => zone.id === zoneA), false);
  assert.equal((await request('/api/floor/zones', 'POST', { expectedVenueId: venueA, name: 'Wrong Venue Zone' })).status, 409);
  assert.equal((await request('/api/floor/tables', 'POST', { expectedVenueId: venueA, zoneId: zoneA, name: 'Wrong Venue Table', capacity: 2 })).status, 409);
