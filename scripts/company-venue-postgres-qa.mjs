    assert.equal(racingSelect.status, 200, JSON.stringify(racingSelect.body));
    await blocker.query('COMMIT');
    const racingResult = await racingSave;
    assert.equal(racingResult.status, 409, JSON.stringify(racingResult.body));
    const racingZoneResult = await racingZone;
    assert.equal(racingZoneResult.status, 409, JSON.stringify(racingZoneResult.body));
    assert.equal((await pool.query("SELECT count(*)::int AS count FROM zones WHERE venue_id=$1 AND name='Late Zone Into A'", [venueA])).rows[0].count, 0);
    assert.equal((await pool.query('SELECT name FROM venues WHERE id=$1', [venueA])).rows[0].name, 'QA Venue A');
