import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const app=read('app.js'),css=read('style.css');
const start=app.indexOf('const staffManagementShellRole='),end=app.indexOf('\n',start);
assert.ok(start>=0&&end>start);
const ctx=vm.createContext({});vm.runInContext(app.slice(start,end)+';globalThis.subject=staffManagementShellRole;',ctx);
for(const role of ['owner','admin','manager','developer'])assert.equal(ctx.subject(role),true);
for(const role of ['bartender','hookah_master','senior_bartender','senior_hookah_master','cleaner','security','technician','other_staff','staff','unknown',null,undefined])assert.equal(ctx.subject(role),false);
const applySessionStart=app.indexOf('const applyStaffSession=(s)=>{if(!s?.user)return;const actor=s.user;');
const applySessionEnd=app.indexOf('\nconst resolveStaticStaffPermissions=',applySessionStart);
assert.ok(applySessionStart>=0&&applySessionEnd>applySessionStart,'Staff session application boundary');
const applySessionBlock=app.slice(applySessionStart,applySessionEnd);
assert.ok(applySessionBlock.includes("document.body.classList.toggle('staff-management-shell',staffManagementShellRole(actor.role));"),'Marker derives from session actor');
const permissionBoundary=applySessionBlock.indexOf('const permissions=new Set(');
assert.ok(permissionBoundary>0,'Permission application boundary');
assert.equal([...applySessionBlock.slice(0,permissionBoundary).matchAll(/staffManagementShellRole/g)].length,2,'Cosmetic helper stays before permission application');
assert.equal([...applySessionBlock.slice(permissionBoundary).matchAll(/staffManagementShellRole/g)].length,0,'Cosmetic helper cannot alter permission grants');
const markerUses=[...app.matchAll(/staffManagementShellRole/g)];assert.equal(markerUses.length,3,'Cosmetic shell helper use stays bounded');
const blockStart=css.indexOf('/* UI-03.1:'),blockEnd=css.indexOf('/* UI-04.1 C11/C13:',blockStart);
assert.ok(blockStart>=0&&blockEnd>blockStart,'UI-03.1 shell block boundaries');
const block=css.slice(blockStart,blockEnd);
assert.ok(block.includes('@media(min-width:901px)'));
for(const v of ['--crm-shell-sidebar-width:clamp(210px,18vw,280px)','--crm-shell-sidebar-padding:clamp(14px,1.2vw,22px)','--crm-shell-header-padding:clamp(18px,2.4vw,38px)','--crm-shell-sidebar-width:210px','height:var(--crm-header-height);min-height:var(--crm-header-height)','padding-inline:var(--crm-shell-header-padding)','flex:0 0 auto','[role="button"]'])assert.ok(block.includes(v),v);
assert.ok(!block.includes('!important'));
assert.match(block,/\.header-context\s*\{\s*display:flex;align-items:center;gap:4px;/);
assert.match(block,/\.header-context>\.muted\s*\{\s*flex:0 1 auto;min-width:0;overflow:hidden;text-overflow:ellipsis;/);
assert.match(block,/\.header-context>b\s*\{\s*flex:0 0 auto;/);
assert.equal(read('dist/app.js'),app);assert.equal(read('dist/style.css'),css);
console.log('UI-03.1 source contract PASS: verified cosmetic role marker, desktop role widths/padding/header, native hit targets and scoped mirrors. Runtime geometry is separate.');
