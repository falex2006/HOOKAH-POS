import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

const packagePath = process.env.PLAYWRIGHT_PACKAGE_PATH;
if (!packagePath) throw new Error('Set PLAYWRIGHT_PACKAGE_PATH');
const { chromium } = createRequire(import.meta.url)(packagePath);
const screenshotDir = process.env.STAFF_PROFILE_SCREENSHOT_DIR ? path.resolve(process.env.STAFF_PROFILE_SCREENSHOT_DIR) : path.resolve('docs/ai-team/responsive-emulator');
await mkdir(screenshotDir, { recursive: true });
const child = spawn(process.execPath, ['server.js'], {
  cwd: fileURLToPath(new URL('../', import.meta.url)), windowsHide: true,
  env: { ...process.env, HOST: '127.0.0.1', PORT: '0', DATABASE_URL: '', AUTH_REQUIRED: 'false', DEMO_MODE: 'false', NODE_ENV: 'test' },
  stdio: ['ignore', 'pipe', 'pipe'],
});
let output = '';
child.stdout.on('data', (chunk) => { output += chunk; });
child.stderr.on('data', (chunk) => { output += chunk; });
let browser;
try {
  const base = await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`Staff profile QA server did not start: ${output}`)), 15000);
    child.once('error', reject);
    child.stdout.on('data', () => { const match = output.match(/CRM running on http:\/\/localhost:(\d+)/); if (match) { clearTimeout(timer); resolve(`http://127.0.0.1:${match[1]}`); } });
  });
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 375, height: 800 }, locale: 'ru-RU' });
  const exceptions = [];
  const staffApiResponses = [];
  page.on('pageerror', (error) => exceptions.push(error.message));
  page.on('response', async (response) => {
    const url = new URL(response.url());
    if (url.pathname !== '/api/staff') return;
    let body = null;
    try { body = await response.json(); } catch (_) {}
    staffApiResponses.push({ method: response.request().method(), status: response.status(), body });
  });
  await page.goto(`${base}/login`, { waitUntil: 'networkidle' });
  await page.locator('#login-username').fill('admin');
  await page.locator('#login-password').fill('admin');
  await page.locator('#login-form button[type="submit"]').click();
  await page.waitForURL((url) => !url.pathname.includes('/login'));
  await page.goto(`${base}/admin#staff`, { waitUntil: 'networkidle' });
  await page.locator('.staff-add-button').click();
  const roleSelect = page.locator('#staff-role');
  assert.equal(await page.locator('#staff-form').evaluate((form) => { const fields = ['#staff-name', '#staff-birth-date', '#staff-role', '#staff-login', '#staff-password', '#staff-photo', '#staff-phone-primary', '#staff-telegram', '#staff-employment-started', '#staff-work-notes'].map((selector) => form.querySelector(selector)); return fields.every((field, index) => Boolean(field) && fields.slice(index + 1).every((next) => field.compareDocumentPosition(next) & Node.DOCUMENT_POSITION_FOLLOWING)); }), true, 'role and its access fields appear before optional photo and contact details');
  assert.equal(await roleSelect.inputValue(), '', 'new employee role requires an explicit choice');
  assert.equal(await roleSelect.evaluate((node) => node.validity.valueMissing), true, 'empty role is blocked by native required validation');
  assert.equal(await page.locator('#staff-login').isVisible(), false, 'account fields stay hidden until a CRM role is selected');
  await page.locator('#staff-name').fill('QA Работник зала');
  await page.locator('#staff-birth-date').fill('2000-01-01');
  await page.locator('#staff-form button[type="submit"]').click();
  assert.equal(await roleSelect.evaluate((node) => document.activeElement === node), true, 'submit focuses the role that still needs a choice');
  assert.equal(staffApiResponses.some((entry) => entry.method === 'POST'), false, 'missing role sends no create request');
  await roleSelect.selectOption('bartender');
  assert.equal(await page.locator('#staff-login').isVisible(), true, 'CRM role reveals account fields');
  assert.equal(await page.locator('#staff-password').evaluate((node) => node.required), true, 'CRM role requires a temporary password');
  await roleSelect.selectOption('cleaner');
  assert.equal(await page.locator('#staff-login').isVisible(), false, 'non-CRM role hides account fields');
  const createStaffResponse = page.waitForResponse((response) => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/staff');
  await page.locator('#staff-form button[type="submit"]').click();
  assert.equal((await createStaffResponse).status(), 201, 'creating a non-CRM employee succeeds before profile QA');
  const row = page.locator('#staff-list .staff-row').filter({ hasText: 'QA Работник зала' });
  try { await row.waitFor({ timeout: 5000 }); }
  catch (_) { throw new Error(`Created staff did not appear in the list: ${JSON.stringify({ staffApiResponses, list: await page.locator('#staff-list').innerText() })}`); }
  await page.reload({ waitUntil: 'networkidle' });
  const refreshedRow = page.locator('#staff-list .staff-row').filter({ hasText: 'QA Работник зала' });
  await refreshedRow.waitFor();
  const directoryControls = page.locator('#staff .staff-directory-view-controls');
  assert.equal(await directoryControls.isVisible(), false, 'mobile shows one staff layout without view or card-size controls');
  assert.equal(await page.locator('#staff-list').getAttribute('data-view'), 'list', 'mobile renders the single list layout');
  await page.setViewportSize({ width: 1024, height: 800 });
  await directoryControls.waitFor({ state: 'visible' });
  await directoryControls.locator('[data-staff-view="table"]').click();
  assert.equal(await page.locator('#staff-list').getAttribute('data-view'), 'table', 'desktop can select and render table view');
  await page.setViewportSize({ width: 768, height: 900 });
  assert.equal(await directoryControls.isVisible(), false, 'unfolded-phone/tablet-width viewport keeps one staff layout');
  await page.waitForFunction(() => document.querySelector('#staff-list')?.dataset.view === 'list');
  assert.equal(await page.locator('#staff-list').getAttribute('data-view'), 'list', 'unfolded-phone/tablet-width viewport renders list despite saved desktop preference');
  assert.equal(await page.locator('#staff-list .staff-table-scroll').count(), 0, 'mobile list avoids the wide table scroller');
  await page.setViewportSize({ width: 1024, height: 800 });
  assert.equal(await directoryControls.isVisible(), true, 'desktop view controls return after resizing');
  await page.waitForFunction(() => document.querySelector('#staff-list')?.dataset.view === 'table');
  assert.equal(await page.locator('#staff-list').getAttribute('data-view'), 'table', 'desktop preference returns after resizing back');
  await page.setViewportSize({ width: 375, height: 800 });
  assert.equal(await directoryControls.isVisible(), false, 'phone viewport remains on the single list layout');
  await page.locator('#staff-search').fill('QA Работник');
  assert.equal(await page.locator('#staff-list .staff-row:visible').count(), 1);
  await refreshedRow.locator('.staff-card-primary.staff-edit').click();
  const modal = page.locator('.staff-admin-modal');
  await modal.waitFor();
  assert.equal(await modal.locator('[name="role"]').inputValue(), 'cleaner', 'opening card preserves non-CRM role');
  assert.equal(await modal.getAttribute('role'), 'dialog');
  assert.equal(await modal.getAttribute('aria-modal'), 'true');
  assert.equal(await modal.locator('[name="name"]').evaluate((node) => document.activeElement === node), true, 'card focuses first editable field');
  const roleDropdown = modal.locator('[name="role"]').locator('..');
  const roleTrigger = roleDropdown.locator('.custom-select-trigger');
  await modal.locator('[name="workNotes"]').fill('Черновик до закрытия списка');
  await roleTrigger.click();
  await page.keyboard.press('Escape');
  assert.equal(await modal.count(), 1, 'first Escape closes only the role menu');
  assert.equal(await roleTrigger.getAttribute('aria-expanded'), 'false');
  assert.equal(await roleTrigger.evaluate((node) => document.activeElement === node), true, 'menu Escape restores its trigger');
  assert.equal(await modal.locator('[name="role"]').inputValue(), 'cleaner', 'closing role menu preserves selection');
  assert.equal(await modal.locator('[name="workNotes"]').inputValue(), 'Черновик до закрытия списка', 'menu Escape preserves the card draft');
  await roleTrigger.click();
  await roleTrigger.focus();
  await page.keyboard.press('Escape');
  assert.equal(await modal.count(), 1, 'Escape on the open trigger also keeps the card');
  assert.equal(await roleTrigger.getAttribute('aria-expanded'), 'false');
  await page.keyboard.press('Escape');
  await modal.waitFor({ state: 'detached' });
  assert.equal(await refreshedRow.locator('.staff-card-primary.staff-edit').evaluate((node) => document.activeElement === node), true, 'second Escape on the closed trigger returns to the opener');
  await refreshedRow.locator('.staff-card-primary.staff-edit').click();
  await modal.waitFor();
  const assertStaffActionOrder = async (mobile) => modal.evaluate((root, mobile) => {
    const footer = root.querySelector('.staff-admin-actions');
    const [cancel, save] = [...footer.querySelectorAll('button')].map((button) => button.getBoundingClientRect());
    return mobile ? cancel.top < save.top && Math.abs(cancel.left - save.left) < 2 && Math.abs(cancel.width - save.width) < 2 : cancel.left < save.left;
  }, mobile);
  for (const width of [320, 375, 640]) {
    await page.setViewportSize({ width, height: 800 });
    await modal.locator('.staff-admin-actions').scrollIntoViewIfNeeded();
    assert.equal(await assertStaffActionOrder(true), true, `staff card actions follow DOM order and share a full row at ${width}px`);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `staff card has no horizontal overflow at ${width}px`);
    if (width === 375) await page.screenshot({ path: path.join(screenshotDir, 'staff-card-actions-375.png') });
  }
  await page.setViewportSize({ width: 641, height: 800 });
  assert.equal(await assertStaffActionOrder(false), true, 'staff card desktop actions retain their horizontal order');
  await page.setViewportSize({ width: 375, height: 800 });
  await modal.locator('[type="submit"]').focus();
  await page.keyboard.press('Tab');
  assert.equal(await modal.locator('.staff-admin-close').evaluate((node) => document.activeElement === node), true, 'Tab wraps inside card');
  await page.keyboard.press('Escape');
  await modal.waitFor({ state: 'detached' });
  assert.equal(await refreshedRow.locator('.staff-card-primary.staff-edit').evaluate((node) => document.activeElement === node), true, 'Escape returns focus to opener');
  await page.evaluate(() => { portalUser.role = 'owner'; });
  await refreshedRow.locator('.staff-card-primary.staff-edit').click();
  await modal.waitFor();
  const passportDisclosure = modal.locator('.staff-admin-passport details');
  assert.equal(await passportDisclosure.evaluate((node) => node.open), false, 'sensitive passport fields start collapsed');
  assert.equal(await modal.locator('[name="passport_number"]').isVisible(), false, 'passport fields are hidden until requested');
  await passportDisclosure.locator('summary').click();
  assert.equal(await passportDisclosure.evaluate((node) => node.open), true, 'owner can expand passport fields');
  assert.equal(await modal.locator('[name="passport_number"]').isVisible(), true, 'passport fields remain available to the owner');
  assert.equal(await modal.locator('[name="role"]').inputValue(), 'cleaner', 'owner card must not silently select admin');
  assert.equal(await modal.locator('.staff-admin-identity small').textContent(), 'Уборщица / уборщик');
  await modal.locator('.staff-admin-close').click();
  await page.evaluate(() => { portalUser.role = 'admin'; });
  await refreshedRow.locator('.staff-card-primary.staff-edit').click();
  await modal.waitFor();
  await modal.locator('[name="workNotes"]').fill('QA график: 2/2');
  await modal.locator('[type="submit"]').click();
  await modal.waitFor({ state: 'detached' });
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('#staff-list .staff-row').filter({ hasText: 'QA Работник зала' }).locator('.staff-card-primary.staff-edit').click();
  await modal.waitFor();
  assert.equal(await modal.locator('[name="role"]').inputValue(), 'cleaner');
  assert.equal(await modal.locator('[name="workNotes"]').inputValue(), 'QA график: 2/2');
  let profilePatchCount = 0;
  page.on('request', (request) => { if (request.method() === 'PATCH' && request.url().includes('/api/staff/') && request.url().endsWith('/profile')) ++profilePatchCount; });
  let pendingStaffGetRoute;
  let signalStaffGet;
  const staffGetStarted = new Promise((resolve) => { signalStaffGet = resolve; });
  await page.route('**/api/staff', (route) => { pendingStaffGetRoute = route; signalStaffGet(); });
  await modal.locator('[name="workNotes"]').fill('QA график: 3/3');
  await modal.locator('[type="submit"]').click();
  await staffGetStarted;
  await modal.waitFor({ state: 'detached' });
  assert.equal(await page.locator('#staff-list .staff-row').filter({ hasText: 'QA Работник зала' }).locator('.staff-card-primary.staff-edit').evaluate((node) => document.activeElement === node), true, 'focus stays on card opener while refresh waits');
  await pendingStaffGetRoute.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'temporary_unavailable' }) });
  await page.locator('#staff-list .staff-list-retry').waitFor();
  assert.equal(await page.locator('#portal-notice').textContent(), 'Карточка сохранена, но список не обновился. Повторите загрузку списка.');
  assert.equal(profilePatchCount, 1, 'failed refresh must not repeat profile PATCH');
  await page.unroute('**/api/staff');
  await page.locator('.staff-list-retry').click();
  // This persistent error notice has no close control in the QA fixture; remove it before the next independent click.
  await page.locator('#portal-notice').evaluate((node) => node.remove());
  await page.locator('#staff-list .staff-row').filter({ hasText: 'QA Работник зала' }).locator('.staff-card-primary.staff-edit').click();
  await modal.waitFor();
  assert.equal(await modal.locator('[name="workNotes"]').inputValue(), 'QA график: 3/3');
  const rejectProfilePatch = (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'temporary_unavailable' }) });
  await page.route('**/api/staff/*/profile', rejectProfilePatch);
  await modal.locator('[name="workNotes"]').fill('QA график: 4/4');
  await modal.locator('[type="submit"]').click();
  await modal.locator('.staff-admin-message').getByText(/Не удалось сохранить карточку/).waitFor();
  assert.equal(await modal.count(), 1, 'PATCH failure keeps card open');
  assert.equal(await modal.locator('[type="submit"]').isEnabled(), true);
  await page.unroute('**/api/staff/*/profile', rejectProfilePatch);
  await modal.locator('[type="submit"]').click();
  await modal.waitFor({ state: 'detached' });
  await page.locator('#staff-list .staff-row').filter({ hasText: 'QA Работник зала' }).locator('.staff-card-primary.staff-edit').click();
  await modal.waitFor();
  assert.equal(await modal.locator('[name="workNotes"]').inputValue(), 'QA график: 4/4');
  assert.equal(profilePatchCount, 3, 'retry sends only one additional PATCH');
  await page.setViewportSize({ width: 320, height: 800 });
  for (let index = 0; index < 4; index += 1) await modal.locator('.staff-admin-add').click();
  assert.equal(await modal.locator('.staff-admin-phone-row').count(), 5);
  assert.equal(await modal.locator('.staff-admin-add').isDisabled(), true);
  assert.equal(await modal.locator('.staff-admin-box').evaluate((node) => node.scrollWidth > node.clientWidth + 1), false, 'filled staff card fits 320px');
  assert.equal(await modal.locator('.staff-admin-phone-row').first().evaluate((row) => row.querySelector('input[type="tel"]').getBoundingClientRect().top > row.querySelector('.custom-select').getBoundingClientRect().top), true, '320px phone fields stack for readability');
  assert.equal(await modal.locator('.staff-admin-phone-row .custom-select-trigger').first().evaluate((node) => node.getBoundingClientRect().width >= 140), true, 'phone type selector remains readable at 320px');
  await modal.locator('.staff-admin-box').screenshot({ path: path.join(screenshotDir, 'staff-profile-open-320.png') });
  await modal.locator('.staff-admin-cancel').click();
  const activeRow = page.locator('#staff-list .staff-row').filter({ hasText: 'QA Работник зала' });
  await activeRow.locator('.staff-delete').click();
  await page.locator('.action-modal.open .action-footer button[type="submit"]').click();
  await page.locator('#staff-list .staff-row.inactive').filter({ hasText: 'QA Работник зала' }).waitFor();
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('#staff-status-filter').selectOption('inactive');
  const blockedRow = page.locator('#staff-list .staff-row.inactive').filter({ hasText: 'QA Работник зала' });
  await blockedRow.waitFor();
  await blockedRow.locator('.staff-restore').click();
  await page.locator('#staff-status-filter').selectOption('active');
  await page.locator('#staff-list .staff-row:not(.inactive)').filter({ hasText: 'QA Работник зала' }).waitFor();
  assert.deepEqual(exceptions.filter((message) => !message.includes('ViewTransition opt-in disabled')), []);
  console.log('STAFF PROFILE BROWSER QA: PASS (real memory CRUD/reload, PATCH/GET failure boundaries, retry, non-CRM role, responsive single mobile list, desktop preference restore, 320px filled card)');
} finally {
  await browser?.close();
  child.kill();
  if (child.exitCode === null) await Promise.race([once(child, 'exit'), new Promise((resolve) => setTimeout(resolve, 3000))]);
}
