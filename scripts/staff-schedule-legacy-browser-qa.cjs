'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {randomUUID} = require('node:crypto');
const {Pool} = require('pg');
const {config,folder,options} = require('./staff-schedule-local-config.cjs');
const {preview,apply} = require('../staff-schedule-copy');
const service = require('../staff-schedule-service');
const {chromium} = require(process.env.PLAYWRIGHT_PACKAGE_PATH || 'playwright');
async function main() {
  const c=config(),f=JSON.parse(fs.readFileSync(path.join(folder,'fixtures.json'),'utf8'));
  const pool=new Pool(options(c)),employee=randomUUID(),base=`http://127.0.0.1:${c.appPort}`;
  let browser, page;
  try {
    await pool.query("INSERT INTO users(id,venue_id,organization_id,full_name,login,role) VALUES($1,$2,$3,'Legacy incomplete QA',$4,'bartender')",[employee,f.venues[0],f.organizations[0],`${employee}@example.test`]);
    const row=(await pool.query("INSERT INTO staff_schedules(venue_id,user_id,work_date,note) VALUES($1,$2,'2026-11-10','Original legacy note') RETURNING id",[f.venues[0],employee])).rows[0];
    const principal={userId:f.users[0].id,venueId:f.venues[0]};
    const query={sourceFrom:'2026-11-09',targetFrom:'2026-11-16',userIds:[employee]};
    const copy=await preview(pool,principal,query);
    assert.equal(copy.items[0].conflict,'schedule_plan_incomplete');
    await assert.rejects(apply(pool,principal,{...query,fingerprint:copy.fingerprint,sourceIds:[row.id],requestKey:randomUUID()}),e=>e.code==='schedule_copy_conflict');
    browser=await chromium.launch({channel:'msedge',headless:true});
    const context=await browser.newContext({viewport:{width:1440,height:1000}}),errors=[];
    page=await context.newPage();
    page.on('pageerror',e=>errors.push(e.message));
    const login=await context.request.post(base+'/api/login',{data:{username:f.users[0].login,password:f.password}});
    assert.equal(login.status(),200);
    await context.addInitScript(({token,user})=>{localStorage.setItem('crm_session_token',token);localStorage.setItem('crm_session_user',JSON.stringify(user));},await login.json());
    await page.goto(base+'/admin#staff-schedule');
    await page.locator('[data-context]').filter({hasText:'Asia/Yekaterinburg'}).waitFor({state:'attached'});
    await page.locator('[data-person]').selectOption(employee);
    await page.locator('[data-date]').fill('2026-11-10');
    await page.locator('[data-date]').dispatchEvent('change');
    await page.locator('[data-context]').filter({hasText:'План неполный: 1'}).waitFor({state:'attached'});
    assert.ok((await page.locator('[data-context]').innerText()).includes('0 ч по плану'));
    assert.ok(!(await page.locator('[data-context]').innerText()).includes('NaN'));
    await page.locator(`[data-entry="${row.id}"]:visible`).click();
    const dialog=page.locator('dialog[open]');
    assert.equal(await dialog.locator('[name=start]').inputValue(),'');
    assert.equal(await dialog.locator('[name=end]').inputValue(),'');
    await dialog.locator('[name=start]').fill('2026-11-10T10:00');
    await dialog.locator('[name=end]').fill('2026-11-10T18:00');
    await dialog.locator('[name=reason]').fill('Уточнение старого плана');
    await service.save(pool,principal,{userId:employee,workDate:'2026-11-10',plannedStart:'2026-11-10T12:00+05:00',plannedEnd:'2026-11-10T19:00+05:00',note:'Изменено параллельно',reason:'QA',version:1,requestKey:randomUUID()},row.id);
    const stale=page.waitForResponse(r=>r.url().endsWith('/'+row.id)&&r.request().method()==='PATCH');
    await dialog.getByRole('button',{name:'Сохранить',exact:true}).click();
    assert.equal((await stale).status(),409);
    await dialog.getByText('Запись изменена другим пользователем',{exact:true}).waitFor();
    assert.equal(await dialog.locator('[name=start]').inputValue(),'2026-11-10T10:00');
    assert.equal(await dialog.locator('[name=note]').inputValue(),'Original legacy note');
    await dialog.getByRole('button',{name:'Применить мой черновик к новой версии',exact:true}).click();
    const saved=page.waitForResponse(r=>r.url().endsWith('/'+row.id)&&r.request().method()==='PATCH');
    await dialog.getByRole('button',{name:'Сохранить',exact:true}).click();
    assert.equal((await saved).status(),200);
    await page.locator('[data-context]').filter({hasText:'8 ч по плану'}).waitFor({state:'attached'});
    const event=(await pool.query('SELECT before_data,after_data FROM staff_schedule_events WHERE schedule_id=$1 ORDER BY id',[row.id])).rows[0];
    assert.equal(event.before_data.planned_start,null);
    assert.equal(event.before_data.note,'Original legacy note');
    assert.ok(event.after_data.planned_start);
    assert.deepEqual(errors,[]);
    assert.equal((await pool.query('SELECT version,note FROM staff_schedules WHERE id=$1',[row.id])).rows[0].version,3);
    await page.locator(`[data-entry="${row.id}"]:visible`).click();
    await dialog.locator('[name=note]').fill('Черновик после отмены');
    await service.save(pool,principal,{status:'cancelled',version:3,reason:'Параллельная отмена',requestKey:randomUUID()},row.id);
    const cancelledConflict=page.waitForResponse(r=>r.url().endsWith('/'+row.id)&&r.request().method()==='PATCH');
    await dialog.getByRole('button',{name:'Сохранить',exact:true}).click();
    assert.equal((await cancelledConflict).status(),409);
    await dialog.getByText('Запись отменена. Повторное сохранение запрещено; черновик доступен для копирования.',{exact:false}).waitFor();
    assert.equal(await dialog.locator('[name=note]').inputValue(),'Черновик после отмены');
    assert.equal(await dialog.getByRole('button',{name:'Применить мой черновик к новой версии',exact:true}).count(),0);
    assert.equal((await pool.query('SELECT status FROM staff_schedules WHERE id=$1',[row.id])).rows[0].status,'cancelled');
    const discard = page.waitForEvent('dialog').then(async prompt => {
      assert.equal(prompt.type(), 'confirm');
      assert.match(prompt.message(), /несохранённые изменения/i);
      await prompt.accept();
    });
    await dialog.locator('[data-close]').click();
    await discard;
    await dialog.waitFor({state:'detached'});
    await page.locator('[data-cancelled]').check();
    const half=(await pool.query("INSERT INTO staff_schedules(venue_id,user_id,work_date,planned_start) VALUES($1,$2,'2026-11-11','2026-11-11T10:00+05:00') RETURNING id",[principal.venueId,employee])).rows[0];
    await service.save(pool,principal,{status:'cancelled',version:1,reason:'Отмена неполного плана',requestKey:randomUUID()},half.id);
    await page.locator('[data-refresh]').click();
    await page.locator(`[data-entry="${half.id}"]:visible`).click();
    await dialog.getByRole('button',{name:'История изменений',exact:true}).click();
    await dialog.getByText('Окончание не задано',{exact:false}).waitFor();
    assert.ok(!(await dialog.innerText()).includes('1970'));
    await assert.rejects(service.get(pool,{userId:f.users[4].id,venueId:f.venues[1]},row.id),e=>e.code==='schedule_not_found');
    console.log('LEGACY/CONFLICT SCHEDULE: PASS incomplete display/copy rejection, concurrent edit409, latest comparison, draft retained, explicit reapply version3/history; foreign venue GET denied.');
  } catch(error) {
    if(page){
      await page.screenshot({path:path.join(folder,'legacy-browser-failure.png'),fullPage:true});
      console.error(JSON.stringify(await page.evaluate(()=>({status:document.querySelector('[data-status]')?.textContent,guard:document.querySelector('#portal-session-guard')?.textContent}))));
    }
    throw error;
  } finally {await browser?.close();await pool.end();}
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
