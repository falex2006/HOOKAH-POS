import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const migration = read('migrations/095_inventory_categories_tobacco.sql');
const repository = read('db.js'); const server = read('server.js'); const portal = read('portal.js');
assert.match(migration, /FOREIGN KEY\s*\(venue_id,category_id\)\s*REFERENCES product_categories\(venue_id,id\)/i);
assert.match(migration, /match_count=1/i); assert.match(migration, /lower\(btrim\(c\.name\)\)=lower\(btrim\(i\.category\)\)/i);
assert.match(migration, /inventory_category_seed_state[\s\S]*PRIMARY KEY \(venue_id,seed_key\)/i);
for (const key of ['bar.water','bar.soft-drinks','bar.tea-coffee','bar.ingredients','bar.spirits','hookah.tobacco','hookah.coal','hookah.bowls','hookah.hookahs','hookah.flasks','hookah.consumables']) assert.ok(migration.includes(key), `missing category seed ${key}`);
assert.match(migration, /FOREIGN KEY\s*\(organization_id,tobacco_catalog_item_id\)\s*REFERENCES tobacco_catalog_items\(organization_id,id\)/i);
assert.match(migration, /item_scope='venue'[\s\S]*item_venue IS DISTINCT FROM NEW\.venue_id/);
assert.match(repository, /category_id AS "categoryId"[\s\S]*tobacco_catalog_item_id AS "tobaccoCatalogItemId"/);
assert.match(repository, /\['categoryId','category_id'\][\s\S]*\['tobaccoCatalogItemId','tobacco_catalog_item_id'\]/);
assert.match(server, /input\.categoryId[\s\S]*resolveInventoryCategoryId/);
const categoryResolverStart = server.indexOf('const resolveInventoryCategoryId = async');
const categoryResolverEnd = server.indexOf('const validateTobaccoCatalogLink', categoryResolverStart);
assert.ok(categoryResolverStart >= 0 && categoryResolverEnd > categoryResolverStart, 'category resolver must exist');
const categoryResolver = server.slice(categoryResolverStart, categoryResolverEnd);
assert.match(categoryResolver, /WHERE c\.venue_id=\$1 AND c\.department=\$2 AND c\.is_active=true/);
assert.match(categoryResolver, /c\.id=\$3::uuid/);
assert.match(categoryResolver, /lower\(btrim\(c\.name\)\)=lower\(btrim\(\$4\)\)/);
assert.match(categoryResolver, /inventory_category_not_found/);
assert.match(categoryResolver, /inventory_category_ambiguous/);
assert.match(server, /validateTobaccoCatalogLink/);
assert.match(portal, /inventory-item-tobacco-catalog/); assert.match(portal, /categoryId: document\.querySelector\('#inventory-item-category'\)\.value/);
assert.match(portal, /tobaccoCatalogItemId: document\.querySelector\('#inventory-item-tobacco-catalog'\)\.value/);
