import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

export async function verifyPayableRefund({ page, base, api, db, venueId, venueDate, bankId, selectPortalOption }) {
  const title = `QA payable refund ${process.pid}`;
  const category = await api('/api/finance/categories', 'POST', { name: title, kind: 'expense' });
  assert.equal(category.status, 201);
  const created = await api('/api/finance/payables', 'POST', { categoryId: category.body.id, title, counterpartyName: 'QA landlord refunds', basis: 'Refund acceptance', periodFrom: venueDate, periodTo: venueDate, dueDate: venueDate, lines: [{description: 'Rent', amount: '100.00'}], idempotencyKey: randomUUID() });
  assert.equal(created.status, 201, JSON.stringify(created.body));
  const id = created.body.id;
  assert.equal((await api(`/api/finance/payables/${id}`, 'PATCH', {status:'approved'})).status, 200);
  const payment = await api(`/api/finance/payables/${id}/payments`, 'POST', {amount:'100.00', paymentDate:venueDate, paymentMethod:'bank_transfer', paymentAccountId:bankId, idempotencyKey:randomUUID()});
  assert.equal(payment.status, 201, JSON.stringify(payment.body));
  const expenseId = (await db.query('SELECT expense_id FROM finance_payable_payment_links WHERE venue_id=$1 AND payable_id=$2',[venueId,id])).rows[0].expense_id;
  await page.goto(`${base}/finance#business-obligations`, {waitUntil:'networkidle'});
  await page.locator('#business-obligations [data-obligation-from]').fill(venueDate);
  await page.locator('#business-obligations [data-obligation-to]').fill(venueDate);
  await page.locator('#business-obligations [data-obligation-reload]').click();
  const row = page.locator('#business-obligations article.category-row').filter({hasText:title});
  await row.getByText('История оплат', {exact:true}).click();
  await row.locator(`[data-payable-payment-refund="${expenseId}"]`).click();
  const modal = page.getByRole('dialog').filter({hasText:'Зафиксировать возврат денег'});
  await modal.locator('[name="amount"]').fill('30');
  await modal.locator('[name="refundDate"]').fill(venueDate);
  await selectPortalOption(modal.locator('[name="accountMethod"]'),`${bankId}|bank_transfer`);
  await modal.locator('[name="reason"]').fill('Частичный возврат арендодателя');
  const refundPath = `/api/finance/expenses/${expenseId}/refunds`;
  let lost = false;
  await page.route(`**${refundPath}`, async route => {
    const response = await route.fetch();
    if (route.request().method()==='POST' && !lost) { lost=true; await route.fulfill({response,status:503,contentType:'application/json',body:JSON.stringify({error:'simulated_lost_ack'})}); }
    else await route.fulfill({response});
  });
  const ack = page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname===refundPath).catch(async error => { throw new Error(`${error.message}; refund dialog: ${await modal.innerText()}; validity: ${JSON.stringify(await modal.locator('input,select,textarea').evaluateAll(nodes=>nodes.map(n=>({name:n.name,value:n.value,valid:n.validity.valid,message:n.validationMessage}))))}`); });
  await Promise.all([modal.getByRole('button',{name:'Записать поступление',exact:true}).click(), ack.then(response=>assert.equal(response.status(),503))]);
  await page.reload({waitUntil:'networkidle'});
  await row.getByText('История оплат',{exact:true}).click();
  await row.locator(`[data-payable-payment-refund="${expenseId}"]`).click();
  await page.getByText('Возврат уже записан. История сверена.',{exact:true}).waitFor();
  await page.unroute(`**${refundPath}`);
  const list = await api(`/api/finance/payables?from=${venueDate}&to=${venueDate}`);
  const item = list.body.items.find(x=>x.id===id);
  assert.equal(Number(item.paidAmount),100);
  assert.equal(Number(item.refundedAmount),30);
  assert.equal(Number(item.netPaidAmount),70);
  assert.equal(Number(item.balanceDue),30);
  assert.equal(item.paymentStatus,'partially_paid');
  const report = await api(`/api/finance/unified-report?from=${venueDate}&to=${venueDate}&source=expense_refund&categoryId=${category.body.id}&q=${expenseId}`);
  assert.equal(report.status,200,JSON.stringify(report.body));
  assert.equal(report.body.items.expenseRefunds.length,1);
  assert.equal(report.body.items.expenseRefunds[0].payableId,id);
  assert.equal(report.body.items.expenseRefunds[0].pnlEffect,'separate_payable_recognition');
  assert.equal(Number(report.body.items.expenseRefunds[0].amount),30);
  assert.equal(report.body.coverage.manualExpenseRefunds.status,'complete');

  assert.equal((await db.query('SELECT count(*)::int AS count FROM finance_expense_refunds WHERE venue_id=$1 AND payable_id=$2',[venueId,id])).rows[0].count,1);
  assert.equal((await api(`/api/finance/payables/${id}/payments`,'POST',{amount:'31.00',paymentDate:venueDate,paymentMethod:'bank_transfer',paymentAccountId:bankId,idempotencyKey:randomUUID()})).status,409);
  assert.equal((await api(`/api/finance/payables/${id}/payments`,'POST',{amount:'30.00',paymentDate:venueDate,paymentMethod:'bank_transfer',paymentAccountId:bankId,idempotencyKey:randomUUID()})).status,201);
  await page.reload({waitUntil:'networkidle'});
  await row.getByText('Оплачено',{exact:true}).waitFor();
  const destination=await api('/api/finance/payables','POST',{categoryId:category.body.id,title:`${title} destination`,counterpartyName:'QA landlord refunds',basis:'Offset agreement',periodFrom:venueDate,periodTo:venueDate,dueDate:venueDate,lines:[{description:'Next rent',amount:'65.00'}],idempotencyKey:randomUUID()});
  assert.equal(destination.status,201);
  assert.equal((await api(`/api/finance/payables/${destination.body.id}`,'PATCH',{status:'approved'})).status,200);
  await page.reload({waitUntil:'networkidle'});
  await page.locator(`[data-payable-offset="${id}"]`).click();
  const offsetForm=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Зачесть оплату',exact:true})});
  await selectPortalOption(offsetForm.locator('[name="expenseId"]'),expenseId);
  await selectPortalOption(offsetForm.locator('[name="destinationPayableId"]'),destination.body.id);
  await offsetForm.locator('[name="amount"]').fill('20');
  await offsetForm.locator('[name="offsetDate"]').fill(venueDate);
  await offsetForm.locator('[name="reason"]').fill('Перенос оплаты по соглашению');
  await offsetForm.getByRole('button',{name:'Проверить зачёт',exact:true}).click();
  const confirmation=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Подтвердить зачёт',exact:true})});
  assert.match(await confirmation.innerText(),/Долг получателя:.*65.*45/s);
  const offsetPath=`/api/finance/payables/${id}/offsets`;let loseOffset=true;
  await page.route(`**${offsetPath}`,async route=>{const response=await route.fetch();if(route.request().method()==='POST'&&loseOffset){loseOffset=false;await route.fulfill({response,status:503,contentType:'application/json',body:JSON.stringify({error:'simulated_lost_offset_ack'})});}else await route.fulfill({response});});
  const offsetAck=page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname===offsetPath);
  await confirmation.getByRole('button',{name:'Подтвердить',exact:true}).click();
  assert.equal((await offsetAck).status(),503);
  await page.reload({waitUntil:'networkidle'});
  await page.locator(`[data-payable-offset="${id}"]`).click();
  await page.getByText('Зачёт уже записан. История сверена.',{exact:true}).waitFor();
  await page.unroute(`**${offsetPath}`);
  const offsetHistory=(await api(offsetPath)).body;
  assert.equal(offsetHistory.items.length,1);
  assert.equal(offsetHistory.items[0].expenseId,expenseId);
  const balances=(await api(`/api/finance/payables?from=${venueDate}&to=${venueDate}`)).body.items;
  assert.equal(Number(balances.find(x=>x.id===id).balanceDue),20);
  assert.equal(Number(balances.find(x=>x.id===destination.body.id).balanceDue),45);
  await page.locator(`[data-payable-offset-reverse="${id}"]`).click();
  const reversalForm=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Сторно зачёта',exact:true})});
  await selectPortalOption(reversalForm.locator('[name="offsetId"]'),offsetHistory.items[0].id);
  await reversalForm.locator('[name="amount"]').fill('20');
  await reversalForm.locator('[name="offsetDate"]').fill(venueDate);
  await reversalForm.locator('[name="reason"]').fill('Отмена соглашения о переносе');
  await reversalForm.getByRole('button',{name:'Проверить зачёт',exact:true}).click();
  const reversalConfirm=page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Подтвердить сторно зачёта',exact:true})});
  await reversalConfirm.getByRole('button',{name:'Подтвердить',exact:true}).click();
  await reversalConfirm.waitFor({state:'detached'});
  await page.reload({waitUntil:'networkidle'});
  const restored=(await api(`/api/finance/payables?from=${venueDate}&to=${venueDate}`)).body.items;
  assert.equal(Number(restored.find(x=>x.id===id).balanceDue),0);
  assert.equal(Number(restored.find(x=>x.id===destination.body.id).balanceDue),65);
  const offsetsReport=await api(`/api/finance/unified-report?from=${venueDate}&to=${venueDate}&source=payable_offset&q=${expenseId}`);
  assert.equal(offsetsReport.status,200,JSON.stringify(offsetsReport.body));
  assert.equal(offsetsReport.body.items.payableOffsets.length,2);
  assert.ok(offsetsReport.body.items.payableOffsets.every(x=>x.cashEffect==='none'&&x.recognitionEffect==='none'&&x.expenseId===expenseId));
  await page.goto(`${base}/finance/report`,{waitUntil:'networkidle'});
  const reportPanel=page.locator('.finance-unified-report');
  await reportPanel.locator('[data-unified-from]').fill(venueDate);
  await reportPanel.locator('[data-unified-to]').fill(venueDate);
  await selectPortalOption(reportPanel.locator('[data-unified-source]'),'payable_offset');
  await reportPanel.locator('[data-unified-q]').fill(expenseId);
  const snapshotResponse=page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname==='/api/finance/unified-report/snapshots'&&r.request().postDataJSON()?.source==='payable_offset');
  await reportPanel.locator('[data-unified-load]').click();
  assert.equal((await snapshotResponse).status(),201);
  const offsetGroup=reportPanel.locator('.report-source-group').filter({hasText:'Зачёты оплат · неденежные распределения'});
  await offsetGroup.locator('summary').click();
  await offsetGroup.locator('.report-row').nth(1).waitFor();
  assert.equal(await offsetGroup.locator('.report-row').count(),2);
  assert.match(await offsetGroup.innerText(),/денежный эффект 0/);
  assert.ok((await offsetGroup.innerText()).includes(expenseId));
  for(const width of [320,768]){await page.setViewportSize({width,height:900});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,`offset controls fit at ${width}`);}
  await page.setViewportSize({width:1440,height:900});

}
