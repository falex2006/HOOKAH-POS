import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../portal.js',import.meta.url),'utf8');
const start=source.indexOf("  if (path === '/api/tobacco-catalog'");
const end=source.indexOf("  if (path === '/api/session/preferences'",start);
assert.ok(start>0&&end>start);
const state={networkCurrentId:'A'},user={role:'owner'},permissions=new Set(['inventory']);let saved=0;
const api=new Function('demoState','portalUser','portalPermissions','hasPortalPermission','demoDefaultVenue','demoSave','window',`return async(url,method='GET',input={})=>{const path=new URL(url,window.location.origin).pathname;${source.slice(start,end)}throw Error('unknown_route');}`)(state,user,permissions,(permission)=>permissions.has(permission),{id:'A'},()=>saved++,{location:{origin:'http://qa.local'}});
assert.deepEqual((await api('/api/tobacco-catalog')).items,[]);
const input={scope:'venue',brand:'QA',flavor:'Мята',aliases:['Mint'],packageGrams:100};
const local=await api('/api/tobacco-catalog','POST',input);
await assert.rejects(api('/api/tobacco-catalog','POST',input),/duplicate/);
const shared=await api('/api/tobacco-catalog','POST',{...input,scope:'organization',flavor:'Лимон',aliases:[]});
assert.equal((await api('/api/tobacco-catalog?q=mint')).items[0].id,local.id);
state.networkCurrentId='B';assert.deepEqual((await api('/api/tobacco-catalog')).items.map(x=>x.id),[shared.id]);
await assert.rejects(api(`/api/tobacco-catalog/${local.id}`,'PATCH',{active:false}),/not_found/);
user.role='manager';await assert.rejects(api(`/api/tobacco-catalog/${shared.id}`,'PATCH',{active:false}),/network_admin_required/);
user.role='owner';state.networkCurrentId='A';
await api(`/api/tobacco-catalog/${local.id}`,'PATCH',{active:false});
assert.equal((await api('/api/tobacco-catalog?status=archived')).items[0].id,local.id);
await api(`/api/tobacco-catalog/${local.id}`,'PATCH',{active:true});
assert.equal((await api('/api/tobacco-catalog')).items.length,2);
permissions.clear();await assert.rejects(api('/api/tobacco-catalog','POST',input),/forbidden/);
assert.equal(saved,4);
console.log('TOBACCO CATALOG DEMO QA: PASS (actual branches, search, duplicate, venue isolation, roles, archive/restore)');
