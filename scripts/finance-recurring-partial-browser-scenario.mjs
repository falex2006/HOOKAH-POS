import assert from 'node:assert/strict';

// Runs only inside the authenticated, runner-owned payables browser fixture.
export async function verifyRecurringPartialMonth({page,base,api,db,venueId,selectPortalOption}) {
  const name=`QA partial rent ${process.pid}`;
  const category=await api('/api/finance/categories','POST',{name,kind:'expense'});
  assert.equal(category.status,201);
  const categoryId=category.body.id;
  await page.goto(`${base}/finance#business-obligations`,{waitUntil:'networkidle'});
  const panel=page.locator('#business-obligations');
  await panel.locator('[data-rule-new]').click();
  const form=panel.locator('[data-rule-form]');
  await selectPortalOption(form.locator('select[name="categoryId"]'),categoryId);
  await form.locator('[name="title"]').fill(name);
  await form.locator('[name="counterpartyName"]').fill('QA landlord partial');
  await form.locator('[name="basis"]').fill('Inclusive calendar-day lease');
  await form.locator('[name="dayOfMonth"]').fill('5');
  await form.locator('[name="startsOn"]').fill('2032-02-15');
  await form.locator('[name="endsOn"]').fill('2032-03-10');
  assert.equal(await form.locator('[name="partialMonthPolicy"]').inputValue(),'full_months_only');
  await selectPortalOption(form.locator('[name="partialMonthPolicy"]'),'calendar_days');
  await form.locator('[data-line-name]').first().fill('Помещение');
  await form.locator('[data-line-amount]').first().fill('60000');
  await form.locator('[data-line-add]').click();
  await form.locator('[data-line-name]').nth(1).fill('Парковка');
  await form.locator('[data-line-amount]').nth(1).fill('5000');
  assert.equal(await form.locator('[name="amount"]').inputValue(),'65000.00','visible rows calculate the monthly total');
  assert.equal(await form.locator('[name="lines"]').inputValue(),'Помещение | 60000\nПарковка | 5000','visible rows synchronize the submitted lines');
  await form.locator('[name="variableAmount"]').check();
  const createdResponse=page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname==='/api/finance/recurring-rules');
  await form.locator('[type="submit"]').click();
  const created=await createdResponse;
  assert.equal(created.status(),201,'opt-in partial rent is created through the real UI');
  const id=(await created.json()).id;
  await form.waitFor({state:'hidden'});
  await page.reload({waitUntil:'networkidle'});
  const rules=(await api('/api/finance/recurring-rules')).body.items;
  assert.equal(rules.find(item=>item.id===id).partialMonthPolicy,'calendar_days');
  assert.equal(rules.find(item=>item.id===id).startsOn,'2032-02-15');
  await panel.locator('.finance-recurring-rules > summary').click();
  const rule=panel.locator('[data-rule-list] article.category-row').filter({hasText:name});
  await rule.getByText(/Неполные месяцы: по календарным дням/).waitFor();
  assert.equal((await api(`/api/finance/recurring-rules/${id}/generate`,'POST',{from:'2032-02',to:'2032-02'})).status,409,'partial generation requires an explicit preview confirmation');
  await panel.locator('[data-obligation-from]').fill('2032-02-01');
  await panel.locator('[data-obligation-to]').fill('2032-02-29');
  await panel.locator('[data-obligation-reload]').click();
  const previewResponse=page.waitForResponse(r=>r.request().method()==='GET'&&new URL(r.url()).pathname===`/api/finance/recurring-rules/${id}/generate-preview`);
  await rule.locator('[data-rule-generate]').click();
  const preview=await (await previewResponse).json();
  assert.equal(preview.periods[0].amount,'33620.69');
  assert.equal(preview.periods[0].dueDate,'2032-02-15');
  assert.deepEqual(preview.periods[0].lines.map(line=>line.amount),['31034.48','2586.21']);
  const dialog=page.locator('.action-modal[role="dialog"]').last();
  const previewText=await dialog.locator('[name="generationPreview"]').inputValue();
  assert.match(previewText,/15\/29 дней/);assert.match(previewText,/33\s*620[,.]69/);assert.match(previewText,/Помещение/);
  const generationResponse=page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname===`/api/finance/recurring-rules/${id}/generate`);
  await dialog.locator('[type="submit"]').click();
  const generated=await generationResponse;
  assert.equal(generated.status(),200);
  const generatedBody=await generated.json(),payableId=generatedBody.items[0].id;
  const confirmedRequest=generated.request().postDataJSON();
  const replay=await api(`/api/finance/recurring-rules/${id}/generate`,'POST',confirmedRequest);
  assert.equal(replay.status,200);assert.equal(replay.body.items[0].id,payableId);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM finance_payables WHERE venue_id=$1 AND recurring_rule_id=$2 AND period_key=$3',[venueId,id,'2032-02'])).rows[0].n,1);
  const stored=(await db.query('SELECT total_amount::text,period_from::text,period_to::text,proration_snapshot FROM finance_payables WHERE venue_id=$1 AND id=$2',[venueId,payableId])).rows[0];
  assert.equal(stored.total_amount,'33620.69');assert.equal(stored.period_from,'2032-02-15');assert.equal(stored.period_to,'2032-02-29');
  assert.equal(stored.proration_snapshot.coveredDays,15);assert.equal(stored.proration_snapshot.monthDays,29);
  await assert.rejects(db.query("UPDATE finance_recurring_rules SET partial_month_policy='full_months_only' WHERE venue_id=$1 AND id=$2",[venueId,id]),/partial_policy_immutable/);
  await assert.rejects(db.query('UPDATE finance_payables SET proration_snapshot=NULL WHERE venue_id=$1 AND id=$2',[venueId,payableId]),/proration_snapshot_immutable/);
  await page.reload({waitUntil:'networkidle'});
  await panel.locator('[data-obligation-from]').fill('2032-02-01');await panel.locator('[data-obligation-to]').fill('2032-02-29');await panel.locator('[data-obligation-reload]').click();
  const payable=panel.locator('[data-obligation-list] article.category-row').filter({hasText:name});
  await payable.locator('[data-proration-origin]').filter({hasText:'15/29 дней'}).waitFor();
  for(const width of [320,768]){
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,`partial-period finance UI fits ${width}px`);
  }
  await page.setViewportSize({width:1440,height:1000});
  // A changed final boundary must invalidate the preview even though the month remains eligible.
  const marchBefore=await api(`/api/finance/recurring-rules/${id}/generate-preview?from=2032-03&to=2032-03`);
  assert.equal(marchBefore.body.periods[0].amount,'20967.74');
  const endPreview=await api(`/api/finance/recurring-rules/${id}/end-date-preview?endsOn=2032-03-20`);
  assert.equal(endPreview.status,200);
  const changedBoundary=endPreview.body.periodChanges.find(item=>item.periodKey==='2032-03');
  assert.equal(changedBoundary.availability,'coverage_changes','far-future boundary remains disclosed beyond the 12-month horizon');
  assert.equal(changedBoundary.previousAmount,'20967.74');assert.equal(changedBoundary.proposedAmount,'41935.49');
  assert.equal((await api(`/api/finance/recurring-rules/${id}`,'PATCH',{action:'set_end_date',endsOn:'2032-03-20',impactToken:endPreview.body.impactToken})).status,200);
  const stale=await api(`/api/finance/recurring-rules/${id}/generate`,'POST',{from:'2032-03',to:'2032-03',previewToken:marchBefore.body.previewToken,idempotencyKey:`partial-stale-${process.pid}`});
  assert.equal(stale.status,409);assert.equal(stale.body.error,'finance_generation_preview_stale');
  const versionPayload={effectiveFrom:'2032-03-01',amount:'70000.00',lines:[{description:'Помещение',amount:'65000.00'},{description:'Парковка',amount:'5000.00'}],variableAmount:false};
  const ratePreview=await api(`/api/finance/recurring-rules/${id}/versions/preview`,'POST',versionPayload);
  assert.equal(ratePreview.status,200);assert.equal(ratePreview.body.projectedPeriods[0].coveredDays,20);assert.equal(ratePreview.body.projectedPeriods[0].proposedAmount,'45161.29');
  assert.equal((await api(`/api/finance/recurring-rules/${id}/versions`,'POST',{...versionPayload,previewToken:ratePreview.body.previewToken,idempotencyKey:`partial-rate-${process.pid}`})).status,201);
  const finalPreview=await api(`/api/finance/recurring-rules/${id}/generate-preview?from=2032-03&to=2032-03`);
  assert.equal(finalPreview.body.periods[0].amount,'45161.29');
  const concurrentPayload={from:'2032-03',to:'2032-03',previewToken:finalPreview.body.previewToken,idempotencyKey:`partial-generate-${process.pid}`};
  const concurrent=await Promise.all([api(`/api/finance/recurring-rules/${id}/generate`,'POST',concurrentPayload),api(`/api/finance/recurring-rules/${id}/generate`,'POST',concurrentPayload)]);
  assert.deepEqual(concurrent.map(item=>item.status),[200,200]);assert.equal(concurrent[0].body.items[0].id,concurrent[1].body.items[0].id);
  // Variable invoices may replace the estimate, but must be explicitly checked and never prorated twice.
  assert.equal((await api(`/api/finance/payables/${payableId}`,'PATCH',{status:'approved'})).status,409);
  const actualLines=[{description:'Фактический счёт',amount:'33600.00'}];
  assert.equal((await api(`/api/finance/payables/${payableId}`,'PATCH',{categoryId,title:name,counterpartyName:'QA landlord partial',basis:'Actual invoice',periodFrom:'2032-02-15',periodTo:'2032-02-29',dueDate:'2032-02-15',lines:actualLines})).status,200);
  const approved=await api(`/api/finance/payables/${payableId}`,'PATCH',{status:'approved',confirmVariableAmount:true,expectedTotalAmount:'33600.00',expectedLines:actualLines});
  assert.equal(approved.status,200);assert.equal(Number(approved.body.totalAmount),33600);
  const preserved=(await db.query('SELECT total_amount::text,proration_snapshot FROM finance_payables WHERE venue_id=$1 AND id=$2',[venueId,payableId])).rows[0];
  assert.deepEqual(preserved.proration_snapshot,stored.proration_snapshot,'rate/term edits and actual invoice confirmation preserve the initial calculation');
  assert.equal(preserved.total_amount,'33600.00');
}
