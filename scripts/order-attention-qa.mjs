import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs';
const { orderAttentionReasons } = createRequire(import.meta.url)('../order-attention.js');
const server = fs.readFileSync('server.js', 'utf8');
const portal = fs.readFileSync('portal.js', 'utf8');
const db = fs.readFileSync('db.js', 'utf8');
assert.match(server, /attentionOnly/);
assert.match(server, /orderAttentionReasons/);
assert.match(db, /attentionPaymentDue/);
assert.match(portal, /order\.attentionReasons/);
assert.match(portal, /Требует внимания:/);
assert.match(server, /active_shift_required/);
assert.match(portal, /Сначала требуют внимания/);
assert.match(portal, /orders-date/);
assert.deepEqual(orderAttentionReasons({ status: 'open' }), ['order_open']);
assert.deepEqual(orderAttentionReasons({ status: 'in_progress' }), ['order_in_progress']);
assert.deepEqual(orderAttentionReasons({ status: 'ready' }), ['order_ready']);
assert.deepEqual(orderAttentionReasons({ status: 'closed', attentionPaymentDue: 10 }), ['payment_due']);
assert.deepEqual(orderAttentionReasons({ status: 'closed', attentionPaymentDue: 0 }), []);
assert.deepEqual(orderAttentionReasons({ status: 'closed', attentionPaymentDue: 0.004 }), []);
assert.deepEqual(orderAttentionReasons({ status: 'closed', attentionPaymentDue: 0.01 }), ['payment_due']);
assert.deepEqual(orderAttentionReasons({ status: 'closed', attentionPaymentDue: 30 }), ['payment_due'], 'a partially paid closed order with a frozen remainder remains visible for reconciliation');
assert.deepEqual(orderAttentionReasons({ status: 'cancelled', attentionPaymentDue: 100, depositBalance: 1000 }), [], 'cancelled orders are not treated as customer-payable from stale snapshots or guest wallet balances');
assert.deepEqual(orderAttentionReasons({ status: 'cancelled', depositBalance: 1000 }), [], 'an unrelated guest wallet balance is not an order attention fact');
console.log('ORDER ATTENTION QA: active statuses, cent rounding, frozen unpaid snapshot, cancelled rows and unrelated guest balances');
