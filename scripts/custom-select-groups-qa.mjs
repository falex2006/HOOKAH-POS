import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../portal.js',import.meta.url),'utf8');
const a=source.indexOf('const portalSelectOptionsMarkup =');
const b=source.indexOf('const enhancePortalSelect =',a);
const esc=value=>String(value??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#039;'}[c]));
const render=new Function('esc',source.slice(a,b)+';return portalSelectOptionsMarkup;')(esc);
const option=(value,text,disabled=false)=>({tagName:'OPTION',value,textContent:text,disabled,selected:false});
const children=[option('','Выберите'),{tagName:'OPTGROUP',label:'Зал <A>',disabled:false,children:[option('a','Стол 1'),option('b','Стол 2',true)]},{tagName:'OPTGROUP',label:'Зал B',disabled:true,children:[option('c','Стол 1')]}];
const html=render({disabled:false,children});
const pendingHtml=render({disabled:true,children});
assert.equal((html.match(/role="group"/g)||[]).length,2);
assert.match(html,/aria-label="Зал &lt;A&gt;"/);
assert.match(html,/data-value="a" aria-selected="false">Стол 1/);
assert.match(html,/data-value="b"[^>]* disabled aria-disabled="true"/);
assert.match(html,/data-value="c"[^>]* disabled aria-disabled="true"/);
assert.match(pendingHtml,/data-value="a"[^>]* disabled aria-disabled="true"/);
assert.match(pendingHtml,/data-value=""[^>]* disabled aria-disabled="true"/);
assert.match(source,/select\.labels \|\| \[\]/);
assert.match(source,/if \(select\.disabled \|\| !option \|\| option\.disabled\) return/);
assert.match(source,/if \(select\.disabled\) \{ event\.preventDefault\(\); return; \}/);
assert.match(source,/if \(select\.disabled\) close\(\)/);
assert.match(source,/const options = \[\.\.\.menu\.querySelectorAll\('\[data-value\]:not\(:disabled\)'\)\]/);
console.log('CUSTOM SELECT GROUPS QA: PASS (group labels, intrinsic disabled options/groups, all options disabled during pending, delegated click/keyboard guards, closed menu)');
