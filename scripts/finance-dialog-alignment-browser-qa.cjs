const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {spawn} = require('node:child_process');
const {once} = require('node:events');
const {randomUUID, randomBytes, scryptSync} = require('node:crypto');
const {Client} = require('pg');
const {chromium} = require(process.env.PLAYWRIGHT_PACKAGE_PATH || 'playwright');

(async () => {
  const {validateQaDatabaseUrl, assertQaDatabaseIdentity} = await import('./postgres-qa-safety.mjs');
  const target = validateQaDatabaseUrl(process.env.FINANCE_DIALOG_ALIGNMENT_TEST_DATABASE_URL, 'FINANCE_DIALOG_ALIGNMENT_TEST_DATABASE_URL');
  assert.match(target.database, /^payables_qa_[a-f0-9]{16}$/i);
  assert.equal(target.database, process.env.LOCAL_FULL_PG_OWNED_DATABASE, 'only the guarded runner may own this disposable database');
  const client = new Client({connectionString:target.url.href, connectionTimeoutMillis:5000});
  const ids={organization:randomUUID(),venue:randomUUID(),owner:randomUUID()};
  const login='finance-dialog-owner-'+ids.owner;
  const password=randomBytes(16).toString('hex');
  const salt=randomBytes(16).toString('hex');
  const hash=`scrypt$${salt}$${scryptSync(password,salt,64).toString('hex')}`;
  const useDist=process.env.FINANCE_DIALOG_ALIGNMENT_USE_DIST==='1';
  const folder=path.resolve('tmp/finance-dialog-alignment-browser-qa',useDist?'dist':'source');
  fs.mkdirSync(folder,{recursive:true});
  let server,browser;
  try {
    await client.connect();
    const identity=(await client.query(`SELECT current_database() AS database,inet_server_addr()::text AS address,inet_server_port() AS port,COALESCE((SELECT rolsuper FROM pg_roles WHERE rolname=current_user),false) AS superuser`)).rows[0];
    assertQaDatabaseIdentity(identity,target.database,Number(target.url.port||5432),'finance dialog alignment QA');
    await client.query('INSERT INTO organizations(id,name,slug,timezone) VALUES($1,$2,$3,$4)',[ids.organization,'Finance dialog alignment QA','finance-dialog-'+ids.organization,'Asia/Yekaterinburg']);
    await client.query("INSERT INTO organization_subscriptions(organization_id,status) VALUES($1,'trialing')",[ids.organization]);
    await client.query('INSERT INTO venues(id,organization_id,name,timezone) VALUES($1,$2,$3,$4)',[ids.venue,ids.organization,'Finance dialog QA venue','Asia/Yekaterinburg']);
    await client.query("INSERT INTO users(id,organization_id,venue_id,full_name,login,password_hash,role,permission_scopes) VALUES($1,$2,$3,'QA owner',$4,$5,'owner','[]'::jsonb)",[ids.owner,ids.organization,ids.venue,login,hash]);
    await client.query("INSERT INTO organization_memberships(organization_id,user_id,membership_role,status) VALUES($1,$2,'owner','active')",[ids.organization,ids.owner]);
    const expenseCategory=(await client.query("INSERT INTO finance_categories(venue_id,name,kind) VALUES($1,'QA аренда','expense') RETURNING id",[ids.venue])).rows[0].id;
    const incomeCategory=(await client.query("INSERT INTO finance_categories(venue_id,name,kind) VALUES($1,'QA услуги','income') RETURNING id",[ids.venue])).rows[0].id;
    const bank=(await client.query("INSERT INTO finance_accounts(venue_id,code,name,kind,allowed_payment_methods) VALUES($1,'qa-bank','QA банковский счёт','bank',ARRAY['bank_transfer']) RETURNING id",[ids.venue])).rows[0].id;
    server=spawn(process.execPath,['server.js'],{windowsHide:true,env:{...process.env,HOST:'127.0.0.1',PORT:'0',DATABASE_URL:target.url.href,VENUE_ID:ids.venue,AUTH_REQUIRED:'true',DEMO_MODE:'false',NODE_ENV:'test',API_RATE_LIMIT:'10000'},stdio:['ignore','pipe','pipe']});
    const base=await new Promise((resolve,reject)=>{
      let output='';const timer=setTimeout(()=>reject(Error('Finance dialog QA startup timeout')),15000);
      server.stdout.on('data',chunk=>{output+=chunk;const port=output.match(/CRM running on http:\/\/localhost:(\d+)/)?.[1];if(port){clearTimeout(timer);resolve('http://127.0.0.1:'+port);}});
      server.once('error',error=>{clearTimeout(timer);reject(error)});
      server.once('exit',code=>{clearTimeout(timer);reject(Error('Finance dialog QA server exited '+code))});
    });
    const api=async(route,token,method='GET',body,expected=200)=>{
      const response=await fetch(base+route,{method,headers:{authorization:'Bearer '+token,'content-type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
      const data=await response.json();assert.equal(response.status,expected,route+': '+JSON.stringify(data));return data;
    };
    const session=await api('/api/login','','POST',{username:login,password});
    const date=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Yekaterinburg'}).format(new Date());
    const payablePayload=(title,key)=>({categoryId:expenseCategory,title,counterpartyName:'QA арендодатель',basis:'Договор QA',periodFrom:date.slice(0,7)+'-01',periodTo:date,dueDate:date,lines:[{description:'Аренда зала',amount:'25000.00'}],idempotencyKey:key});
    const draft=await api('/api/finance/payables',session.token,'POST',payablePayload('QA черновик договора','finance-dialog-draft-'+ids.owner),201);
    const approved=await api('/api/finance/payables',session.token,'POST',payablePayload('QA утверждённый договор','finance-dialog-approved-'+ids.owner),201);
    await api('/api/finance/payables/'+approved.id,session.token,'PATCH',{status:'approved'});
    const incomePayload=(title,key)=>({categoryId:incomeCategory,title,counterpartyName:'QA контрагент',basis:'Акт QA',recognitionDate:date,totalAmount:'15000.00',idempotencyKey:key});
    const incomeDraft=await api('/api/finance/other-income',session.token,'POST',incomePayload('QA доход на утверждение','finance-dialog-income-draft-'+ids.owner),201);
    const income=await api('/api/finance/other-income',session.token,'POST',incomePayload('QA поступление и возврат','finance-dialog-income-posted-'+ids.owner),201);
    await api(`/api/finance/other-income/${income.id}/post`,session.token,'POST',{});
    const receipt=await api(`/api/finance/other-income/${income.id}/receipts`,session.token,'POST',{amount:'5000.00',receiptDate:date,paymentMethod:'bank_transfer',paymentAccountId:bank,note:'QA аванс',idempotencyKey:'finance-dialog-receipt-'+ids.owner},201);
    assert.ok(receipt.id&&draft.id&&incomeDraft.id);
    browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
    const errors=[];
    const captures=[];
    for(const width of [390,1440]){
      const height=width===390?844:1000;
      const context=await browser.newContext({viewport:{width,height},locale:'ru-RU'});
      const page=await context.newPage();
      page.on('pageerror',error=>errors.push(error.message));
      if(useDist){
        await page.route(/\/portal\.js(?:\?|$)/,route=>route.fulfill({path:path.resolve(__dirname,'../dist/portal.js'),contentType:'text/javascript'}));
        await page.route(/\/style\.css(?:\?|$)/,route=>route.fulfill({path:path.resolve(__dirname,'../dist/style.css'),contentType:'text/css'}));
      }
      await page.goto(base+'/login');
      await page.locator('#login-username').fill(login);
      await page.locator('#login-password').fill(password);
      await page.locator('#login-form button[type="submit"]').click();
      await page.waitForURL(url=>url.pathname!=='/login');
      let financialWrites=0;
      page.on('request',request=>{if(/^(POST|PATCH|DELETE)$/.test(request.method())&&new URL(request.url()).pathname.startsWith('/api/finance/'))financialWrites++});
      const inspect=async(label,root)=>{
        const box=await root.evaluate(node=>{const r=node.getBoundingClientRect();return {left:r.left,right:r.right,width:r.width,top:r.top,bottom:r.bottom}});
        const pageWidth=await page.evaluate(()=>document.documentElement.scrollWidth);
        assert.ok(pageWidth<=width+1,`${label} page horizontal overflow ${width}: ${pageWidth}`);
        assert.ok(box.width>0&&box.left>=-1&&box.right<=width+1,`${label} control outside viewport ${width}: ${JSON.stringify(box)}`);
        await root.screenshot({path:path.join(folder,`${label}-${width}.png`)});
        captures.push(`${label}-${width}`);
      };
      await page.goto(base+'/finance#business-obligations',{waitUntil:'networkidle'});
      const obligations=page.locator('#business-obligations');
      const list=obligations.locator('[data-obligation-list]');
      await list.getByText('QA черновик договора',{exact:false}).waitFor();
      await inspect('obligations-filled',obligations);
      const draftRow=list.locator('article.category-row').filter({hasText:'QA черновик договора'});
      assert.equal(await draftRow.locator(`[data-obligation-approve="${draft.id}"]`).isVisible(),true);
      await obligations.locator('[data-obligation-new]').click();
      const obligationForm=obligations.locator('[data-obligation-form]');
      await obligationForm.waitFor({state:'visible'});
      await inspect('obligation-form',obligationForm);
      const footer=obligationForm.locator('.obligation-form-actions > button');
      assert.equal(await footer.count(),2);
      assert.ok((await footer.evaluateAll(nodes=>nodes.map(node=>node.getBoundingClientRect().height))).every(n=>n>=44));
      await obligationForm.locator('[data-form-close]').click();
      assert.equal(await obligationForm.isVisible(),false);
      await obligations.locator('[data-rule-new]').click();
      const ruleForm=obligations.locator('[data-rule-form]');
      await ruleForm.waitFor({state:'visible'});
      await inspect('rule-form',ruleForm);
      await ruleForm.locator('[data-form-close]').click();
      const approvedRow=list.locator('article.category-row').filter({hasText:'QA утверждённый договор'});
      await approvedRow.waitFor();
      await approvedRow.locator('summary').filter({hasText:'Зафиксировать оплату'}).click();
      const paymentForm=approvedRow.locator(`[data-obligation-payment="${approved.id}"]`);
      await inspect('obligation-payment',paymentForm);
      const paymentLayout=await paymentForm.evaluate(form=>{
        const action=form.querySelector('button[type="submit"]');
        const message=form.querySelector('.form-message');
        const row=form.querySelector('.form-row');
        const style=getComputedStyle(form);
        const available=form.clientWidth-(parseFloat(style.paddingLeft)||0)-(parseFloat(style.paddingRight)||0);
        return {form:form.getBoundingClientRect().toJSON(),action:action.getBoundingClientRect().toJSON(),row:row?.getBoundingClientRect().toJSON(),available,messageEmpty:!message?.textContent.trim(),messageHeight:message?.getBoundingClientRect().height};
      });
      assert.ok(paymentLayout.action.height>=44,`payment action meets touch target ${width}`);
      assert.ok(paymentLayout.messageEmpty&&paymentLayout.messageHeight===0,`empty payment message reserves no height ${width}`);
      if(width===390)assert.ok(paymentLayout.action.width>=paymentLayout.available-2,`mobile payment action uses full form width: ${JSON.stringify(paymentLayout)}`);
      else assert.ok(paymentLayout.action.width>=190,`desktop payment action has minimum width: ${JSON.stringify(paymentLayout)}`);
      await approvedRow.locator('summary').filter({hasText:'Зафиксировать оплату'}).click();
      await page.goto(base+'/finance#other-income',{waitUntil:'networkidle'});
      const incomePanel=page.locator('#other-income');
      const incomeList=incomePanel.locator('[data-other-income-list]');
      await incomeList.getByText('QA поступление и возврат',{exact:false}).waitFor();
      const postedRow=incomeList.locator('.payment-row').filter({hasText:'QA поступление и возврат'});
      await inspect('income-filled',incomePanel);
      await postedRow.locator('.finance-receipt-disclosure > summary').click();
      await inspect('income-receipt',postedRow.locator('[data-other-income-receipt]'));
      await postedRow.locator('.finance-receipt-disclosure > summary').click();
      const history=postedRow.locator(`[data-other-income-history="${income.id}"]`);
      await history.locator(':scope > summary').click();
      const refund=history.locator('[data-other-income-refund]');
      await refund.waitFor({state:'visible'});
      await inspect('income-refund',refund);
      const draftIncomeRow=incomeList.locator('.payment-row').filter({hasText:'QA доход на утверждение'});
      await draftIncomeRow.locator(`[data-other-income-post="${incomeDraft.id}"]`).click();
      const confirm=page.getByRole('dialog');
      await confirm.waitFor({state:'visible'});
      await inspect('income-decision',confirm);
      const decision=confirm.locator('button[type="submit"]');
      assert.equal((await decision.innerText()).trim(),'Провести доход');
      assert.equal(await decision.evaluate(button=>button.classList.contains('primary')&&!button.classList.contains('danger')),true,'posting income is a primary action, not a destructive red action');
      await confirm.getByRole('button',{name:'Отмена'}).click();
      await confirm.waitFor({state:'hidden'});
      assert.equal(financialWrites,0,'visual audit does not submit any finance operation');
      await context.close();
    }
    assert.deepEqual(errors,[],'no uncaught browser errors');
    console.log(`FINANCE DIALOG ALIGNMENT BROWSER QA: PASS (${useDist?'dist':'source'}; ${captures.join(', ')})`);
  }finally{
    if(browser)await browser.close().catch(()=>{});
    if(server && server.exitCode === null && server.signalCode === null){const stopped=once(server,'exit').catch(()=>{});server.kill();await stopped;}
    await client.end().catch(()=>{});
  }
})().catch(error=>{console.error(error);process.exitCode=1});
