import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const {calendarPeriod,pricePeriod}=require('../finance-recurring-calculation');
const rule={startsOn:'2032-02-15',endsOn:'2032-03-10',dayOfMonth:5,partialMonthPolicy:'calendar_days'};
const version={amount:'65000.00',lines:[{description:'Помещение',amount:'60000.00'},{description:'Парковка',amount:'5000.00'}]};
const feb=calendarPeriod(rule,'2032-02');
assert.equal(feb.coveredDays,15);assert.equal(feb.monthDays,29);assert.equal(feb.dueDate,'2032-02-15');
const priced=pricePeriod(feb,version);
assert.equal(priced.amount,'33620.69');assert.deepEqual(priced.lines.map(line=>line.amount),['31034.48','2586.21']);
assert.equal(priced.prorationSnapshot.monthlyAmount,'65000.00');
const march=calendarPeriod({...rule,dayOfMonth:31},'2032-03');
assert.equal(march.coveredDays,10);assert.equal(march.dueDate,'2032-03-31','contractual payment may fall after the service interval');
assert.equal(pricePeriod(march,version).amount,'20967.74');
assert.equal(calendarPeriod({...rule,partialMonthPolicy:undefined},'2032-02').eligible,false,'default does not silently prorate');
assert.equal(calendarPeriod(rule,'2032-04').eligible,false,'no service outside the rule term');
const oneDay=calendarPeriod({...rule,startsOn:'2032-02-29',endsOn:'2032-02-29'},'2032-02');
assert.equal(oneDay.coveredDays,1);assert.equal(pricePeriod(oneDay,{amount:'29.00',lines:[{description:'One day',amount:'29.00'}]}).amount,'1.00');
const half=calendarPeriod({...rule,startsOn:'2032-04-16',endsOn:'2032-04-30'},'2032-04');
assert.equal(pricePeriod(half,{amount:'0.02',lines:[{description:'A',amount:'0.01'},{description:'B',amount:'0.01'}]}).amount,'0.02','each half-kopeck rounds up; header is sum of rounded lines');
assert.equal(pricePeriod(half,{amount:'999999999999.99',lines:[{description:'Maximum',amount:'999999999999.99'}]}).amount,'500000000000.00','large amounts use exact integer rounding');
const full=calendarPeriod({...rule,startsOn:'2032-02-01',endsOn:'2032-02-29',dayOfMonth:31},'2032-02');
assert.equal(full.dueDate,'2032-02-29');assert.equal(pricePeriod(full,version).amount,'65000.00');assert.equal(pricePeriod(full,version).prorationSnapshot,null);
assert.throws(()=>pricePeriod(feb,{...version,amount:'1.00'}),/total_mismatch/);
assert.throws(()=>calendarPeriod({...rule,partialMonthPolicy:'guess'},'2032-02'),/invalid_recurring_partial_month_policy/);
console.log('FINANCE RECURRING CALCULATION CONTRACT: PASS (inclusive dates, leap year, explicit default, exact line rounding, due dates)');
